#!/usr/bin/env node
// Command-line entry for the prerequisite check in src/doctor.mjs: prints it as Markdown or
// JSON, or writes it to a file. Versions and counts only, so the output is safe to commit.
// Exits 1 when a required row is missing. `--live` adds one real call per side
// (src/doctor-live.mjs) and exits 1 when one fails.
import { writeFileSync } from 'node:fs';
import { describeHost, inspectPrerequisites } from '../src/doctor.mjs';
import { liveExitCode, runLiveChecks } from '../src/doctor-live.mjs';

// What each check is called and what the bridge needs it for.
const LABELS = Object.freeze({
  'codex-cli': ['Codex CLI', 'OpenAI-side sessions'],
  'codex-auth': ['Codex CLI sign-in', 'OpenAI-side sessions'],
  'codex-queue-thread': ['Codex: message an existing session', 'exact-session send'],
  'codex-exec-resume': ['Codex: resume a session headless', 'send and collect the reply'],
  'codex-sessions': ['Codex session store', 'history discovery'],
  'claude-cli': ['Claude Code CLI', 'Anthropic-side sessions'],
  'claude-auth': ['Claude Code CLI sign-in', 'Anthropic-side sessions'],
  'claude-resume': ['Claude Code: resume a session headless', 'exact-session send and collect the reply'],
  'claude-sessions': ['Claude Code session store', 'history discovery'],
  'codex-app': ['Codex desktop app', 'Codex window'],
  'claude-app': ['Claude desktop app', 'Claude window'],
  'chatgpt-app': ['ChatGPT desktop app', 'optional; web chats otherwise live in the browser'],
  chrome: ['Chrome', 'optional web-chat adapters'],
  edge: ['Edge', 'optional web-chat adapters'],
  node: ['Node.js', 'bridge runtime'],
  'state-folder': ['Bridge state folder', 'ledger and mailbox'],
  git: ['git', 'shared source and revisions'],
  'github-cli': ['GitHub CLI', 'publishing'],
  tailscale: ['Tailscale', 'only the Agent Tincan route'],
  wsl: ['WSL', 'only the Agent Tincan route'],
});

const labelled = (checks) => checks.map((c) => ({ component: LABELS[c.id]?.[0] ?? c.id, neededFor: LABELS[c.id]?.[1] ?? '', ...c }));

const NOT_PROBED = [
  'Plan of the ChatGPT and Claude accounts.',
  'Whether a message sent from the CLI appears in the desktop app windows.',
  'Where the Claude desktop app keeps Code-tab transcripts.',
  'Browser extensions and web-chat sign-in state.',
];

function toMarkdown(rows, host, date) {
  const cell = (value) => String(value ?? '').replaceAll('|', '\\|');
  return [
    '# Environment snapshot',
    '',
    `Generated by \`node tools/doctor.mjs --write docs/environment.md\` on ${date}.`,
    'Versions and counts only: no paths, user names or message content.',
    '',
    `Host: ${host}`,
    '',
    '| Component | Needed for | Status | Version | Note |',
    '|---|---|---|---|---|',
    ...rows.map((r) => `| ${cell(r.component)} | ${cell(r.neededFor)} | ${r.status} | ${cell(r.version ?? '-')} | ${cell(r.note)} |`),
    '',
    '## Not probed',
    '',
    ...NOT_PROBED.map((item) => `- ${item}`),
    '',
  ].join('\n');
}

// Printed only, never written to the snapshot file: it is a run, not a snapshot.
function liveMarkdown(live) {
  const said = (s) => (s.appOpened !== null ? String(s.appOpened) : s.side === 'claude' ? 'none' : 'not applicable');
  return [
    '',
    '## Live check',
    '',
    '| Side | Peer | Command line found | Answered | app.opened | Result | Detail |',
    '|---|---|---|---|---|---|---|',
    ...live.sides.map((s) => `| ${s.side} | ${s.peer} | ${s.cliFound} | ${s.answered} | ${said(s)} | ${s.ok ? 'pass' : 'FAIL'} | ${s.detail.replaceAll('|', '\\|')} |`),
    '',
  ].join('\n');
}

async function main(args) {
  const { ok, checks } = inspectPrerequisites();
  const rows = labelled(checks);
  // Only with --live is anything called.
  const live = args.includes('--live') ? await runLiveChecks({ checks }) : null;
  // 1 when a required row is missing or a live side failed.
  const exitCode = Math.max(ok ? 0 : 1, live ? liveExitCode(live) : 0);
  const host = describeHost();
  const date = new Date().toISOString().slice(0, 10);
  if (args.includes('--json')) {
    console.log(JSON.stringify({ host, date, rows, ...(live ? { live } : {}) }, null, 2));
    return exitCode;
  }
  const markdown = toMarkdown(rows, host, date);
  const writeAt = args.indexOf('--write');
  if (writeAt === -1) {
    process.stdout.write(markdown + (live ? liveMarkdown(live) : ''));
    return exitCode;
  }
  const target = args[writeAt + 1];
  if (!target || target.startsWith('--')) {
    console.error('usage: doctor.mjs [--json | --write <file>] [--live]');
    return 2;
  }
  writeFileSync(target, markdown);
  console.log(`wrote ${target}${live ? liveMarkdown(live) : ''}`);
  return exitCode;
}

main(process.argv.slice(2)).then((code) => {
  process.exitCode = code;
});
